const CLASSIC_CELL = /^[XO.]{9}$/;

function classicBoardFrom(text) {
  if (typeof text !== "string" || !CLASSIC_CELL.test(text)) return null;
  return xox.from_text(text);
}

// ===========================================================================
// The message pump
// ===========================================================================

// One job at a time. `queue` holds requests that arrived while a job was
// running; `current` is the running one. `cancel` and `ping` jump the queue,
// because a cancel that waited its turn behind the search it is cancelling
// would be useless.
const queue = [];
let current = null;
let draining = false;

function post(message) {
  self.postMessage(message);
}

function respondError(id, code, message) {
  post({ id: id, type: "error", code: code, message: message });
}

// AC-44: every response echoes the request id. A request that arrived without
// a usable integer id still gets an answer — with `id: null`, so a client can
// at least log it — and the worker stays alive.
function idOf(data) {
  return data && Number.isInteger(data.id) ? data.id : null;
}

function isRequestType(type) {
  return type === "choose" || type === "legalMoves" || type === "applyMove" || type === "ping" || type === "cancel";
}

function onMessage(data) {
  const id = idOf(data);

  if (data === null || typeof data !== "object") {
    respondError(id, "BadRequest", "message payload is not an object");
    return;
  }

  // Out of band: answered immediately, even mid-search.
  if (data.type === "cancel") {
    handleCancel(id, data);
    return;
  }
  if (data.type === "ping") {
    post({ id: id, type: "pong", buildAt: builtAt });
    return;
  }
  if (!isRequestType(data.type)) {
    respondError(id, "BadRequest", `unknown type ${JSON.stringify(data.type ?? null)}`);
    return;
  }

  queue.push({ id: id, request: data, cancelled: false });
  void drain();
}

function handleCancel(id, data) {
  // `target` omitted means "whatever is in flight" — that is what
  // engine-client's `engine.cancel()` sends.
  const target = Number.isInteger(data.target) ? data.target : current ? current.id : null;

  if (current !== null && current.id === target) {
    // The running job checks this flag at its next ply boundary and answers
    // `cancelled` in its own id. It will never answer `chosen` (§3.3).
    current.cancelled = true;
  } else {
    // Not running yet: drop it from the queue and close it out here, so the
    // client's promise for that id still settles exactly once.
    const at = queue.findIndex((job) => job.id === target);
    if (at >= 0) {
      const [job] = queue.splice(at, 1);
      post({ id: job.id, type: "cancelled", target: job.id });
    }
  }

  // The ack for the cancel request itself. Idempotent: cancelling an id that
  // already finished is not an error.
  post({ id: id, type: "cancelled", target: target });
}

async function drain() {
  if (draining) return;
  draining = true;
  try {
    while (queue.length > 0) {
      current = queue.shift();
      try {
        await runJob(current);
      } catch (err) {
        // AC-44: nothing thrown inside a job may kill the worker.
        respondError(current.id, "Internal", String((err && err.message) || err));
      }
      current = null;
    }
  } finally {
    draining = false;
  }
}

async function runJob(job) {
  const req = job.request;
  switch (req.type) {
    case "choose":
      return await handleChoose(job, req);
    case "legalMoves":
      return handleLegalMoves(job, req);
    case "applyMove":
      return handleApplyMove(job, req);
    default:
      respondError(job.id, "BadRequest", `unknown type ${JSON.stringify(req.type ?? null)}`);
      return undefined;
  }
}

// Decode the wire state, or answer `error` and return null. A decode failure
// is a normal response, never a throw (§3.3).
function decodeOrFail(job, text) {
  if (typeof text !== "string") {
    respondError(job.id, "BadRequest", "state must be a string");
    return null;
  }
  const d = decode(text);
  if (!d.ok) {
    respondError(job.id, "BadState", `cannot decode state: ${d.error}`);
    return null;
  }
  return d.state;
}

async function handleChoose(job, req) {
  const mode = req.mode === "classic" ? "classic" : "ultimate";
  const level = typeof req.level === "string" ? req.level : "hard";
  const difficulty = difficultyOf(level);
  const seed = normalizeSeed(req.seed);
  const budgetMs = normalizeBudget(req.budgetMs);
  const startedAt = now();

  if (mode === "classic") return handleClassicChoose(job, req, difficulty, startedAt);

  const state = decodeOrFail(job, req.state);
  if (state === null) return;

  if (isTerminal(state)) {
    post({ id: job.id, type: "rejected", error: { code: "GameOver", detail: {} } });
    return;
  }

  const { plan, cancelled } = await chooseMoveChunked(state, difficulty, seed, budgetMs, job);

  if (cancelled || job.cancelled) {
    post({ id: job.id, type: "cancelled", target: job.id });
    return;
  }
  if (plan === null) {
    post({ id: job.id, type: "rejected", error: { code: "GameOver", detail: {} } });
    return;
  }

  // Belt and braces: the engine, not the search, has the last word on whether
  // the move is playable. If this ever rejects, the bug is reported rather
  // than played (FR-3.4).
  const applied = applyMove(state, plan.move);
  if (!applied.ok) {
    post({ id: job.id, type: "rejected", error: applied.error });
    return;
  }

  post({
    id: job.id,
    type: "chosen",
    move: plan.move,
    score: plan.score,
    depth: plan.depth,
    nodes: plan.nodes,
    elapsedMs: Math.round(now() - startedAt),
    state: encode(applied.state),
  });
}

function handleClassicChoose(job, req, difficulty, startedAt) {
  const board = classicBoardFrom(req.state);
  if (board === null) {
    respondError(job.id, "BadState", "classic state must be 9 characters of X, O or .");
    return;
  }
  const turn = cellFromJs(req.turn);
  if (turn === null) {
    respondError(job.id, "BadRequest", 'classic choose needs turn: "X" or "O"');
    return;
  }
  if (xox.outcome(board).tag !== "Ongoing") {
    post({ id: job.id, type: "rejected", error: { code: "GameOver", detail: {} } });
    return;
  }

  const picked = ai.classic_choose(board, turn, difficulty);
  if (picked.tag !== "Some") {
    post({ id: job.id, type: "rejected", error: { code: "GameOver", detail: {} } });
    return;
  }
  if (job.cancelled) {
    post({ id: job.id, type: "cancelled", target: job.id });
    return;
  }

  const square = picked.value;
  post({
    id: job.id,
    type: "chosen",
    move: { square: square },
    score: 0,
    depth: 0,
    nodes: 0,
    elapsedMs: Math.round(now() - startedAt),
    state: xox.to_text(xox.place(board, square, turn)),
  });
}

function handleLegalMoves(job, req) {
  const state = decodeOrFail(job, req.state);
  if (state === null) return;
  post({ id: job.id, type: "result", value: getLegalMoves(state) });
}

function handleApplyMove(job, req) {
  const state = decodeOrFail(job, req.state);
  if (state === null) return;

  const m = req.move;
  if (m === null || typeof m !== "object" || !Number.isFinite(m.board) || !Number.isFinite(m.cell)) {
    respondError(job.id, "BadRequest", "move must be { board, cell }");
    return;
  }

  const applied = applyMove(state, { board: m.board, cell: m.cell });
  if (!applied.ok) {
    // AC-43: an illegal move is a normal response carrying the MoveError tag
    // verbatim. It never throws and never kills the worker.
    post({ id: job.id, type: "rejected", error: applied.error });
    return;
  }
  post({ id: job.id, type: "result", value: { state: encode(applied.state) } });
}

// ---------------------------------------------------------------------------
// Install. Guarded so `import`ing this module from node (a js-test, or the
// build's smoke step) gets the facade without a message pump.
// ---------------------------------------------------------------------------

const inWorkerScope =
  typeof self !== "undefined" &&
  typeof self.postMessage === "function" &&
  typeof self.addEventListener === "function";

if (inWorkerScope) {
  self.addEventListener("message", (event) => {
    try {
      onMessage(event.data);
    } catch (err) {
      // The outermost net. Whatever happened, the worker answers and lives.
      respondError(idOf(event.data), "Internal", String((err && err.message) || err));
    }
  });
  post({ id: READY_ID, type: "ready", buildAt: builtAt });
}
