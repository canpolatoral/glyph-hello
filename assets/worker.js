// worker.js — the engine Web Worker (module worker).
//
// Owner: Protocol. This is the ONLY place the AI search ever runs (FR-4.4:
// the main thread must never block), and the only place tagged unions become
// plain JSON (nothing with a `.tag` ever crosses postMessage).
//
// Layering, per specs/architecture.md §3.1:
//
//     engine-client.js  ──postMessage──►  worker.js
//                                             │  direct import
//                                             ▼
//                          assets/engine/ultimate_ai.js
//                                   └► ultimate.js └► xox.js
//
// `assets/engine/**` is generated by `node tools/build-web.mjs`; it is the
// Glyph engine compiled to browser ES modules with every specifier rewritten
// to a relative `.js` path, so there is no import map, no bundler and no
// network fetch at runtime (G-4).
//
// NOTE ON engine-api.js. specs/architecture.md gives the tagged-union facade
// its own file, imported by both threads. That file has no owner in this
// phase, so the facade lives here and is exported. When engine-api.js does
// land it is a straight lift of the "facade" section below, and this file
// re-exports from it instead.
//
// EXACTLY SIX EXPORTS, and that is normative: spec AC-42 says "the worker
// module exposes exactly the names getLegalMoves, applyMove, getWinner,
// isTerminal (plus getOutcome, chooseMove)", and test-matrix TW-005 checks it
// by set equality — "extras fail too". So encode/decode and the pump's own
// helpers stay module-private. A js-test that wants the pump without a real
// Worker installs a stub scope before importing:
//
//     globalThis.self = { postMessage: fn, addEventListener: (t, h) => {…} };
//     const w = await import("./worker.js");   // pump installs, posts `ready`
//
// which is exactly how tools/js-tests can drive it under `node --test`.
//
// This file must never touch the DOM and must never import a node-only
// module. `tools/build-web.mjs` step 5 audits the generated engine for that;
// this file is hand-written and stays inside the same rules.

import * as ultimate from "./engine/ultimate.js";
import * as ai from "./engine/ultimate_ai.js";
import * as xox from "./engine/xox.js";
import { builtAt } from "./engine/build-info.js";

// ---------------------------------------------------------------------------
// Tunables
// ---------------------------------------------------------------------------

// FR-4.5's hard cap, and the spec's depth ceiling for Hard (D-A6). `deepen`
// inside ultimate_ai.glyph uses the same 12.
const MAX_DEPTH = 12;

// Before starting ply d, the deepening loop demands that the remaining budget
// exceed `factor * (cost of ply d-1)`. `ultimate_ai.deepen` uses a flat 3 here
// (measured per-ply growth on this engine is 2.5x-4.2x), and it can afford to
// guess low because it also passes a deadline into the search and abandons a
// ply that overruns. This loop cannot — `search_at` takes no deadline, so a
// started ply always finishes — so it guesses with the growth it has actually
// observed on THIS position, and only falls back to 3 before there are two
// plies to compare. Clamped so one anomalous ply cannot stall the ladder.
const GROWTH = 3;
const MAX_GROWTH = 8;

const DEFAULT_BUDGET_MS = 1500;
const MAX_BUDGET_MS = 60000;

// The id reserved for the unsolicited `ready` message; never issued to a
// request (specs/architecture.md §3.3).
const READY_ID = 0;

const now =
  typeof performance !== "undefined" && typeof performance.now === "function"
    ? () => performance.now()
    : () => Date.now();

// ===========================================================================
// The facade — the AC-42 surface. `state` here is a live UState; `state` on
// the wire is always the encode() string.
// ===========================================================================

// A Glyph `Cell` as "X" | "O" | null.
function cellToJs(c) {
  return c && (c.tag === "X" || c.tag === "O") ? c.tag : null;
}

// "X" | "O" -> a Glyph Cell. Anything else is null (the caller reports it).
function cellFromJs(text) {
  if (text === "X") return xox.X;
  if (text === "O") return xox.O;
  return null;
}

// A MoveError variant -> { code, detail }. `code` is the variant tag verbatim
// (GameOver | OutOfRange | WrongBoard | BoardClosed | CellTaken), which is the
// AC-43 contract; `detail` is every payload field the variant carried.
function moveErrorToJs(e) {
  const detail = {};
  for (const key of Object.keys(e)) {
    if (key !== "tag") detail[key] = e[key];
  }
  return { code: e.tag, detail: detail };
}

export function getLegalMoves(state) {
  return ultimate.legal_moves(state).map((m) => ({ board: m.board, cell: m.cell }));
}

export function applyMove(state, move) {
  const r = ultimate.apply_move(state, { board: move.board, cell: move.cell });
  return r.tag === "Ok"
    ? { ok: true, state: r.value }
    : { ok: false, error: moveErrorToJs(r.value) };
}

export function getWinner(state) {
  const w = ultimate.winner(state);
  return w.tag === "Some" ? cellToJs(w.value) : null;
}

export function isTerminal(state) {
  return ultimate.is_terminal(state) === true;
}

export function getOutcome(state) {
  const o = ultimate.outcome(state);
  if (o.tag === "Won") {
    return { status: "won", winner: cellToJs(o.winner), line: o.line.slice() };
  }
  if (o.tag === "Drawn") return { status: "drawn", winner: null, line: [] };
  return { status: "playing", winner: null, line: [] };
}

// Module-private, not exported: see the AC-42 note at the top. These are the
// two names engine-api.js will carry in addition to the six.
function encode(state) {
  return ultimate.encode(state);
}

function decode(text) {
  const r = ultimate.decode(text);
  return r.tag === "Ok" ? { ok: true, state: r.value } : { ok: false, error: r.value };
}

// The synchronous single-shot search. Kept so the AC-42 surface is complete
// and so a js-test can call the ladder directly; the worker's own `choose`
// handler uses `chooseMoveChunked` instead, because that one can be cancelled
// between plies.
export function chooseMove(state, level, seed, budgetMs) {
  const plan = ai.choose(state, difficultyOf(level), normalizeSeed(seed), normalizeBudget(budgetMs));
  return plan.tag === "Some" ? planToJs(plan.value) : null;
}

function planToJs(p) {
  return {
    move: { board: p.move.board, cell: p.move.cell },
    score: p.score,
    depth: p.depth,
    nodes: p.nodes,
  };
}

// `difficulty_from` is total and defaults to Hard, so an unrecognised setting
// can never silently weaken the opponent.
function difficultyOf(level) {
  return ai.difficulty_from(typeof level === "string" ? level : "");
}

function normalizeSeed(seed) {
  return Number.isFinite(seed) ? Math.trunc(seed) : 1;
}

function normalizeBudget(budgetMs) {
  if (!Number.isFinite(budgetMs)) return DEFAULT_BUDGET_MS;
  return Math.min(MAX_BUDGET_MS, Math.max(0, Math.trunc(budgetMs)));
}

// ===========================================================================
// Cancellable iterative deepening (FR-4.5 + D-W1)
// ===========================================================================

// Hand the event loop one turn so message events queued behind us get
// delivered. This is what makes cancellation real: JS in a worker is
// single-threaded, so a `cancel` posted while a search is running is not even
// *received* until the search yields. Yielding at ply boundaries is the
// coarsest granularity that still respects "discard an overrunning ply whole"
// (D-A6) — a ply is atomic, so there is nothing finer to yield at.
const yieldToEventLoop = () => new Promise((resolve) => setTimeout(resolve, 0));

// Iterative deepening driven from here rather than inside
// `ultimate_ai.deepen`, for exactly one reason: `deepen` is a single
// synchronous call, and a synchronous call cannot be cancelled. The loop below
// is `deepen` unrolled — same ply-1-before-any-clock-check rule (FR-4.5: a
// zero or negative budget still returns a legal move), same GROWTH guard on
// whether to start the next ply, same "the reported depth is a ply that
// finished" rule (D-A6) — with a yield inserted at each ply boundary.
//
// The one behavioural difference from `deepen`: `search_at` takes no deadline,
// so a ply that is started always runs to completion. `deepen` can abandon a
// ply mid-way and fall back to the previous one. So this loop can return a
// deeper result than `deepen` at the same budget, and can overshoot the budget
// by the amount the started ply exceeded GROWTH x its predecessor. The GROWTH
// guard is what bounds that, and Easy/Medium do not take this path at all.
async function chooseMoveChunked(state, difficulty, seed, budgetMs, job) {
  // Easy makes no search at all and Medium is a fixed depth-3 search; both are
  // a few milliseconds, so they go straight through the engine's own
  // dispatcher and keep byte-identical behaviour with `ai.choose`.
  if (difficulty.tag !== "Hard") {
    const plan = ai.choose(state, difficulty, seed, budgetMs);
    return { plan: plan.tag === "Some" ? planToJs(plan.value) : null, cancelled: false };
  }

  const started = now();

  // Ply 1 runs before any clock check at all, so even budgetMs = 0 comes back
  // with a legal move (FR-4.5).
  let best = ai.search_at(state, 1);
  if (best.tag !== "Some") return { plan: null, cancelled: false };
  let lastPlyMs = now() - started;
  let prevPlyMs = 0;

  for (let depth = 2; depth <= MAX_DEPTH; depth++) {
    await yieldToEventLoop();
    if (job.cancelled) return { plan: null, cancelled: true };

    // Growth measured on this position, when there are two plies to compare.
    const observed = prevPlyMs > 0.5 ? lastPlyMs / prevPlyMs : GROWTH;
    const factor = Math.min(MAX_GROWTH, Math.max(GROWTH, observed));

    const remaining = budgetMs - (now() - started);
    if (!(remaining > lastPlyMs * factor + 1)) break;

    const plyStart = now();
    const next = ai.search_at(state, depth);
    prevPlyMs = lastPlyMs;
    lastPlyMs = now() - plyStart;
    if (next.tag !== "Some") break; // terminal, or nothing left to search
    best = next;
  }

  return { plan: planToJs(best.value), cancelled: false };
}

